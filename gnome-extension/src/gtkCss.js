// Generate GTK CSS from a theme bundle and apply it to GTK3/4 apps via the
// GTK_CSS_PROVIDER, and to Flatpak apps via an override.

import GLib from 'gi://GLib';

const FLATPAK_OVERRIDE_DIR = GLib.build_filenamev([GLib.get_home_dir(), '.local', 'share', 'flatpak', 'overrides', 'global']);

/** Convert hex colour to GTK CSS rgba() or plain hex. */
function _c(hex, alpha = null) {
    if (alpha === null)
        return hex;
    const r = parseInt(hex.slice(1, 3), 16);
    const g = parseInt(hex.slice(3, 5), 16);
    const b = parseInt(hex.slice(5, 7), 16);
    return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

/** Generate a GTK CSS string from a bundle's colours. */
export function generateGtkCss(bundle) {
    const {colors} = bundle;
    if (!colors)
        return '';

    const _isDark = colors.lightness < 0.5;
    const bg = colors.background;
    const fg = colors.text;
    const accent = colors.accent;
    const surface = colors.surface;
    const surfaceLight = colors.surfaceLight;
    const border = colors.border;
    const error = colors.error;
    const success = colors.success;
    const warning = colors.warning;

    return `
/* Generated by GNOME Island auto-theme for bundle: ${bundle.name} */

@define-color theme_bg_color        ${bg};
@define-color theme_fg_color        ${fg};
@define-color theme_base_color      ${bg};
@define-color theme_text_color      ${fg};
@define-color theme_selected_bg_color ${accent};
@define-color theme_selected_fg_color ${colors.selectionText || bg};
@define-color theme_view_bg_color     ${colors.view || bg};
@define-color theme_view_fg_color     ${fg};
@define-color theme_insensitive_bg_color ${surface};
@define-color theme_insensitive_fg_color ${colors.textMuted || fg};
@define-color theme_border_color      ${border};
@define-color theme_headerbar_bg      ${colors.headerbar || bg};
@define-color theme_headerbar_fg      ${colors.headerbarText || fg};
@define-color theme_sidebar_bg        ${colors.sidebar || surface};
@define-color theme_sidebar_fg        ${fg};
@define-color theme_card_bg           ${colors.card || surfaceLight};
@define-color theme_menu_bg           ${colors.menu || surface};
@define-color theme_menu_fg           ${colors.menuText || fg};
@define-color theme_error_color       ${error};
@define-color theme_success_color     ${success};
@define-color theme_warning_color     ${warning};
@define-color theme_accent_color      ${accent};
@define-color theme_hover_color       ${colors.hover || surfaceLight};

/* ── GTK 3 ──────────────────────────────────────────────────── */

window, dialog, popover, menu, .background {
    background-color: @theme_bg_color;
    color: @theme_fg_color;
}

headerbar, .titlebar {
    background-color: @theme_headerbar_bg;
    color: @theme_headerbar_fg;
    border-color: @theme_border_color;
}

.sidebar, placessidebar, .navigation-sidebar {
    background-color: @theme_sidebar_bg;
    color: @theme_sidebar_fg;
}

.view, .content-view, textview text {
    background-color: @theme_view_bg_color;
    color: @theme_view_fg_color;
}

popover contents, popover.menu, popover.menu box, menu, .context-menu {
    background-color: @theme_menu_bg;
    color: @theme_menu_fg;
}

button, .button {
    background-color: @theme_card_bg;
    color: @theme_fg_color;
    border-color: @theme_border_color;
}
button:hover, .button:hover {
    background-color: @theme_hover_color;
}
button:checked, button:active, .button:checked, .button:active {
    background-color: @theme_selected_bg_color;
    color: @theme_selected_fg_color;
}

entry, spinbutton, textview, textview text {
    background-color: @theme_view_bg_color;
    color: @theme_view_fg_color;
    border-color: @theme_border_color;
}

selection {
    background-color: @theme_selected_bg_color;
    color: @theme_selected_fg_color;
}

.card, .app-card, .tile {
    background-color: @theme_card_bg;
    border-color: @theme_border_color;
}

scrollbar slider {
    background-color: @theme_border_color;
}

/* ── GTK 4 libadwaita / Adwaita overrides ───────────────────── */

window.background, dialog.background {
    background-color: @theme_bg_color;
    color: @theme_fg_color;
}

.adw-toolbar-view headerbar, .adw-header-bar {
    background-color: @theme_headerbar_bg;
    color: @theme_headerbar_fg;
}

.navigation-view .navigation-sidebar, sidebar {
    background-color: @theme_sidebar_bg;
    color: @theme_sidebar_fg;
}

popover > contents {
    background-color: @theme_menu_bg;
    color: @theme_menu_fg;
}

listview row, list row {
    color: @theme_fg_color;
}
listview row:selected, list row:selected {
    background-color: @theme_selected_bg_color;
    color: @theme_selected_fg_color;
}

/* Accent colour for switches, checkboxes, radio buttons */
check, radio, switch {
    color: @theme_accent_color;
}
switch:checked {
    background-color: @theme_accent_color;
}
progressbar trough {
    background-color: @theme_border_color;
}
progressbar progress {
    background-color: @theme_accent_color;
}

/* Error / success / warning labels */
.error {
    color: @theme_error_color;
}
.success {
    color: @theme_success_color;
}
.warning {
    color: @theme_warning_color;
}
`;
}

/** Write the CSS to the user's GTK config so it persists. Returns the path. */
export function installGtkCss(bundle) {
    const css = generateGtkCss(bundle);
    const configDir = GLib.build_filenamev([GLib.get_home_dir(), '.config', 'gtk-4.0']);
    const cssPath = GLib.build_filenamev([configDir, 'gtk-island-auto.css']);
    const gtk3Dir = GLib.build_filenamev([GLib.get_home_dir(), '.config', 'gtk-3.0']);
    const gtk3Path = GLib.build_filenamev([gtk3Dir, 'gtk-island-auto.css']);

    try {
        GLib.mkdir_with_parents(configDir, 0o755);
        GLib.mkdir_with_parents(gtk3Dir, 0o755);
        GLib.file_set_contents(cssPath, new TextEncoder().encode(css));
        GLib.file_set_contents(gtk3Path, new TextEncoder().encode(css));

        // Ensure the CSS is imported in gtk.css / gtk4.css
        ensureImport(configDir, 'gtk-island-auto.css', 'gtk4.css');
        ensureImport(gtk3Dir, 'gtk-island-auto.css', 'gtk.css');

        return {cssPath, gtk3Path};
    } catch (e) {
        log(`isle: could not install GTK CSS: ${e.message}`);
        return null;
    }
}

/** Make sure `importFile` is included in `mainFile`. */
function ensureImport(dir, importFile, mainFile) {
    const mainPath = GLib.build_filenamev([dir, mainFile]);
    let text = '';
    try {
        const [, bytes] = GLib.file_get_contents(mainPath);
        text = new TextDecoder().decode(bytes);
    } catch (e) {
        // file doesn't exist, create it
    }
    const importLine = `@import url("${importFile}");`;
    if (text.includes(importLine))
        return;
    const newText = text + (text.endsWith('\n') || text === '' ? '' : '\n') + importLine + '\n';
    GLib.file_set_contents(mainPath, new TextEncoder().encode(newText));
}

/** Remove the auto-theme CSS imports from gtk.css and gtk4.css. */
export function uninstallGtkCss() {
    for (const [dir, mainFile] of [
        [GLib.build_filenamev([GLib.get_home_dir(), '.config', 'gtk-4.0']), 'gtk4.css'],
        [GLib.build_filenamev([GLib.get_home_dir(), '.config', 'gtk-3.0']), 'gtk.css'],
    ]) {
        const mainPath = GLib.build_filenamev([dir, mainFile]);
        try {
            const [, bytes] = GLib.file_get_contents(mainPath);
            let text = new TextDecoder().decode(bytes);
            text = text.replace(/@import url\("gtk-island-auto\.css"\);\n?/g, '');
            GLib.file_set_contents(mainPath, new TextEncoder().encode(text));
        } catch (e) {
            // ignore
        }
        try {
            const cssPath = GLib.build_filenamev([dir, 'gtk-island-auto.css']);
            if (GLib.file_test(cssPath, GLib.FileTest.EXISTS))
                GLib.unlink(cssPath);
        } catch (e) {
            // ignore
        }
    }
}

/** Apply a Flatpak global override with the theme colours. */
export function installFlatpakOverride(bundle) {
    if (!bundle?.colors)
        return false;
    try {
        const dir = GLib.path_get_dirname(FLATPAK_OVERRIDE_DIR);
        GLib.mkdir_with_parents(dir, 0o755);

        const lines = [
            '[Context]',
            'filesystems=xdg-config/gtk-4.0;xdg-config/gtk-3.0;',
            '',
            '[Environment]',
        ];
        // GTK_THEME env isn't reliable for custom CSS; we rely on the CSS imports above.
        // But we can set a marker env var.
        lines.push('GTK_ISLAND_AUTO_THEME=1');

        const text = lines.join('\n') + '\n';
        GLib.file_set_contents(FLATPAK_OVERRIDE_DIR, new TextEncoder().encode(text));
        return true;
    } catch (e) {
        log(`isle: could not install Flatpak override: ${e.message}`);
        return false;
    }
}

/** Remove the Flatpak global override. */
export function uninstallFlatpakOverride() {
    try {
        if (GLib.file_test(FLATPAK_OVERRIDE_DIR, GLib.FileTest.EXISTS))
            GLib.unlink(FLATPAK_OVERRIDE_DIR);
    } catch (e) {
        // ignore
    }
}
