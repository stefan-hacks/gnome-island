// Apply kitty terminal themes by finding the theme file in kitty's config directories
// and writing it to gnome-island-theme.conf (included by kitty.conf).

import Gio from 'gi://Gio';
import GLib from 'gi://GLib';

/** Common kitty config directories under $HOME. */
function kittyConfigDirs() {
    const home = GLib.get_home_dir();
    return [
        GLib.build_filenamev([home, '.config', 'kitty']),
        GLib.build_filenamev([home, '.kitty']),
    ];
}

/** Case-insensitive search for a theme file named `themeName.conf`. */
function findThemeFile(themeName) {
    const lowerName = themeName.toLowerCase();
    for (const dir of kittyConfigDirs()) {
        // Direct lookup first
        const path = GLib.build_filenamev([dir, `${themeName}.conf`]);
        if (GLib.file_test(path, GLib.FileTest.EXISTS))
            return path;
        // Themes subdirectory — case-insensitive scan
        const themesDir = GLib.build_filenamev([dir, 'themes']);
        if (GLib.file_test(themesDir, GLib.FileTest.IS_DIR)) {
            try {
                const file = Gio.File.new_for_path(themesDir);
                const enumerator = file.enumerate_children('standard::name', Gio.FileQueryInfoFlags.NONE, null);
                let info;
                while ((info = enumerator.next_file(null)) !== null) {
                    const name = info.get_name();
                    if (name.toLowerCase() === `${lowerName}.conf`)
                        return GLib.build_filenamev([themesDir, name]);
                }
            } catch (e) {
                // ignore enumeration errors
            }
        }
    }
    return null;
}

/** Return the kitty themes directory (usually ~/.config/kitty/themes). */
function getThemesDir() {
    for (const dir of kittyConfigDirs()) {
        const themesDir = GLib.build_filenamev([dir, 'themes']);
        if (GLib.file_test(themesDir, GLib.FileTest.IS_DIR))
            return themesDir;
    }
    return null;
}

/** Write text to the gnome-island dynamic theme file. */
function writeIslandThemeFile(text) {
    const home = GLib.get_home_dir();
    const path = GLib.build_filenamev([home, '.config', 'kitty', 'gnome-island-theme.conf']);
    try {
        const bytes = new TextEncoder().encode(text);
        GLib.file_set_contents(path, bytes);
        return true;
    } catch (e) {
        log(`isle: could not write gnome-island-theme.conf: ${e.message}`);
        return false;
    }
}

/** Map bundle kitty names to actual kitty-themes file names where they differ. */
const KITTY_NAME_MAP = {
    'tokyo-night': 'tokyo_night_night',
    'solarized-dark': 'Solarized_Dark',
    'solarized-light': 'Solarized_Light',
    'one-dark': 'OneDark',
    'everforest-dark': 'everforest_dark_medium',
    'night-owl': 'night_owl',
    'dawn': 'Dawnfox',
    'material-deep-ocean': 'OceanicMaterial',
    'atelier-forest': 'atelier-forest-dark',
    'fairy-floss': 'fairyfloss',
};

/** Apply a kitty theme by name. Returns true if the theme was found and applied. */
export function applyKittyTheme(themeName) {
    const mappedName = KITTY_NAME_MAP[themeName.toLowerCase()] || themeName;
    const themePath = findThemeFile(mappedName);
    if (!themePath) {
        log(`isle: kitty theme "${themeName}" (mapped: "${mappedName}") not found`);
        return false;
    }

    // Write the include line to the dynamic theme file instead of modifying
    // kitty.conf (which is a read-only symlink under NixOS home-manager).
    const content = `# Generated by gnome-island auto-theme.\ninclude ${themePath}\n`;
    if (!writeIslandThemeFile(content))
        return false;

    // Signal running kitty instances to reload config and pick up the new theme.
    try {
        Gio.Subprocess.new(['kitty', '@', 'set-colors', '--all', themePath], Gio.SubprocessFlags.NONE);
    } catch (e) {
        // Remote control may not be enabled; config will apply to new windows
    }

    return true;
}

/** Check if a kitty theme file exists for the given name. */
export function kittyThemeExists(themeName) {
    const mappedName = KITTY_NAME_MAP[themeName.toLowerCase()] || themeName;
    return findThemeFile(mappedName) !== null;
}

/** Get the list of available kitty theme names from the themes directory. */
export function listKittyThemes() {
    const themesDir = getThemesDir();
    if (!themesDir)
        return [];
    try {
        const dir = Gio.File.new_for_path(themesDir);
        const enumerator = dir.enumerate_children('standard::name', Gio.FileQueryInfoFlags.NONE, null);
        const themes = [];
        let info;
        while ((info = enumerator.next_file(null)) !== null) {
            const name = info.get_name();
            if (name.endsWith('.conf'))
                themes.push(name.slice(0, -5));
        }
        enumerator.close(null);
        return themes.sort();
    } catch (e) {
        return [];
    }
}
